#!/bin/bash
# =============================================================================
#  Build a lightweight "CodeHaven Workstation.app" bundle (no Electron).
#
#  The bundle is a standard macOS application that runs the Node scanner in the
#  background and opens the workstation UI. It is ad-hoc code signed so it
#  launches on Apple Silicon without the "app is damaged" error.
#
#  Usage: bash scripts/macos/build-macos-app.sh [output-dir]
# =============================================================================
set -euo pipefail

APP_NAME="CodeHaven Workstation"
BUNDLE_ID="app.codehaven.workstation.lite"
VERSION="2.4.0"

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
ROOT="$(cd "$SCRIPT_DIR/../.." && pwd)"
OUT_DIR="${1:-$ROOT/dist}"
APP="$OUT_DIR/$APP_NAME.app"
CONTENTS="$APP/Contents"
MACOS_DIR="$CONTENTS/MacOS"
RES="$CONTENTS/Resources"

echo "Building $APP"

rm -rf "$APP"
mkdir -p "$MACOS_DIR" "$RES/scripts"

# ── Launcher script executed by the bundle ──────────────────────────────────
cat > "$MACOS_DIR/CodeHaven" <<LAUNCHER
#!/bin/bash
# Generated by build-macos-app.sh — do not edit the installed copy.
export CODEHAVEN_HOME="$ROOT"
exec /bin/bash "$RES/scripts/launch-workstation.sh"
LAUNCHER
chmod +x "$MACOS_DIR/CodeHaven"

cp "$SCRIPT_DIR/launch-workstation.sh" "$RES/scripts/launch-workstation.sh"
chmod +x "$RES/scripts/launch-workstation.sh"

# ── Info.plist ──────────────────────────────────────────────────────────────
cat > "$CONTENTS/Info.plist" <<PLIST
<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">
<dict>
  <key>CFBundleName</key><string>$APP_NAME</string>
  <key>CFBundleDisplayName</key><string>$APP_NAME</string>
  <key>CFBundleIdentifier</key><string>$BUNDLE_ID</string>
  <key>CFBundleVersion</key><string>$VERSION</string>
  <key>CFBundleShortVersionString</key><string>$VERSION</string>
  <key>CFBundlePackageType</key><string>APPL</string>
  <key>CFBundleSignature</key><string>????</string>
  <key>CFBundleExecutable</key><string>CodeHaven</string>
  <key>CFBundleIconFile</key><string>AppIcon</string>
  <key>LSMinimumSystemVersion</key><string>10.15</string>
  <key>NSHighResolutionCapable</key><true/>
  <key>LSApplicationCategoryType</key><string>public.app-category.utilities</string>
  <key>NSRequiresAquaSystemAppearance</key><false/>
</dict>
</plist>
PLIST

# ── Icon (only if a usable .icns exists) ────────────────────────────────────
if [[ -f "$ROOT/wallet.icns" ]]; then
  cp "$ROOT/wallet.icns" "$RES/AppIcon.icns"
  echo "  icon: wallet.icns"
elif [[ -f "$ROOT/wallet.ico" ]] && command -v sips >/dev/null 2>&1; then
  TMP_PNG="$RES/icon-source.png"
  if sips -s format png "$ROOT/wallet.ico" --out "$TMP_PNG" >/dev/null 2>&1; then
    ICONSET="$RES/AppIcon.iconset"
    mkdir -p "$ICONSET"
    for size in 16 32 64 128 256 512; do
      sips -z $size $size "$TMP_PNG" --out "$ICONSET/icon_${size}x${size}.png" >/dev/null 2>&1 || true
      double=$((size * 2))
      sips -z $double $double "$TMP_PNG" --out "$ICONSET/icon_${size}x${size}@2x.png" >/dev/null 2>&1 || true
    done
    iconutil -c icns "$ICONSET" -o "$RES/AppIcon.icns" >/dev/null 2>&1 && echo "  icon: generated from wallet.ico"
    rm -rf "$ICONSET" "$TMP_PNG"
  fi
fi

# ── PkgInfo + ad-hoc signature ──────────────────────────────────────────────
printf 'APPL????' > "$CONTENTS/PkgInfo"

if command -v codesign >/dev/null 2>&1; then
  codesign --force --deep --sign - "$APP" >/dev/null 2>&1 \
    && echo "  signed: ad-hoc" \
    || echo "  warning: ad-hoc signing skipped"
fi

xattr -cr "$APP" 2>/dev/null || true

echo "Built: $APP"
echo "Launch with: open \"$APP\""
